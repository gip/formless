#!/usr/bin/env node
/**
 * Generates `lib/generated/starter-files.ts` from the real files under `guest/`.
 *
 * This replaces the `import.meta.glob('../guest/**', { query: '?raw' })` that
 * inlined the guest project while the host built with Vite. Next.js has no
 * equivalent — Turbopack supports neither glob imports nor `?raw` — so the map
 * is generated ahead of the build instead, and checked in so `tsc`, `vitest`,
 * and `next build` all work without a generator step having run first.
 *
 * The output must stay byte-identical to what the glob produced: the extension
 * allowlist, the sort order, and stripping exactly one trailing newline are all
 * load-bearing for `starterPackageHash()`, which pins the 15MB prebuilt runtime
 * snapshot in `public/guest-runtime/`. `tests/runtime-snapshot.test.ts` is the
 * guard.
 */
import { readdir, readFile, mkdir, writeFile } from 'node:fs/promises';
import { dirname, join, relative, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const guestRoot = join(root, 'guest');
const outputPath = join(root, 'lib', 'generated', 'starter-files.ts');

/** Mirrors GUEST_EXTENSIONS in lib/starter-project.ts. */
const GUEST_EXTENSIONS = ['.ts', '.tsx', '.css', '.json', '.html', '.mjs'];

/** Never mount build output or installed packages into the WebContainer. */
const SKIP_DIRECTORIES = new Set(['node_modules', 'dist', '.vite']);

async function collect(directory) {
  const found = [];
  for (const entry of await readdir(directory, { withFileTypes: true })) {
    const absolute = join(directory, entry.name);
    if (entry.isDirectory()) {
      if (SKIP_DIRECTORIES.has(entry.name)) continue;
      found.push(...(await collect(absolute)));
    } else if (GUEST_EXTENSIONS.some((extension) => entry.name.endsWith(extension))) {
      found.push(absolute);
    }
  }
  return found;
}

function stripOneTrailingNewline(contents) {
  return contents.endsWith('\n') ? contents.slice(0, -1) : contents;
}

const files = (await collect(guestRoot)).sort();
const entries = [];
for (const absolute of files) {
  const path = relative(guestRoot, absolute).split('\\').join('/');
  const contents = stripOneTrailingNewline(await readFile(absolute, 'utf8'));
  entries.push(`  ${JSON.stringify(path)}: ${JSON.stringify(contents)},`);
}

const source = `// @generated by scripts/generate-starter-files.mjs — do not edit.
// Run \`pnpm generate:starter\` after changing anything under \`guest/\`.
// ${files.length} files inlined from guest/.

import type { FileMap } from '../canvas-types';

export const GENERATED_STARTER_FILES: FileMap = {
${entries.join('\n')}
};
`;

await mkdir(dirname(outputPath), { recursive: true });
await writeFile(outputPath, source, 'utf8');
console.log(`starter-files.ts: ${files.length} files, ${source.length} bytes`);
